// Keep Codex's skill catalogue inside its budget so descriptions reach the model.
// Why: Codex renders every enabled SKILL.md into every call. Over budget, descriptions are cut to
// a few characters (or dropped), so a skill we rely on (ponytail) is effectively invisible.
// How: disables everything not in KEEP via [[skills.config]] entries between two marker comments
// in ~/.codex/config.toml. Idempotent. Re-run after any `npx skills add` or plugin change:
//   node ~/.claude/tools/codex-skills-prune.mjs            (apply)
//   node ~/.claude/tools/codex-skills-prune.mjs --dry      (report only)
import fs from "fs";
import { execFileSync } from "child_process";

// ponytail: the only per-skill allowlist; edit here, nowhere else.
const KEEP = new Set([
  "imagegen",
  "ponytail:ponytail", "ponytail:ponytail-review", "ponytail:ponytail-audit",
  "impeccable:impeccable", "ui-ux-pro-max:ui-ux-pro-max",
  "pdf:pdf", "21st:21st-cli-use",
  "remotion-best-practices", "hyperframes", "hyperframes-core", "hyperframes-cli", "hyperframes-animation",
  "playwright-cli", "gsap", "design-md", "apple-design", "emil-design-eng",
  "vercel-react-best-practices", "tailwindcss",
]);

const HOME = process.env.USERPROFILE || process.env.HOME;
const CFG = `${HOME}/.codex/config.toml`;
const BEGIN = "# >>> codex-skills-prune (generated by ~/.claude/tools/codex-skills-prune.mjs, do not hand edit)";
const END = "# <<< codex-skills-prune";
const dry = process.argv.includes("--dry");

const strip = (t) => t.replace(new RegExp(`\\n?${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END}\\n?`), "\n");
const cfg0 = fs.readFileSync(CFG, "utf8").replace(/\r\n/g, "\n");
const clean = strip(cfg0);
if (!dry) fs.writeFileSync(CFG, clean); // render the FULL catalogue first

function render() {
  const out = execFileSync("codex", ["debug", "prompt-input", "x"], {
    encoding: "utf8", maxBuffer: 64e6, shell: true,
    env: { ...process.env, PATH: ["C:\\Program Files\\nodejs", `${HOME}\\AppData\\Roaming\\npm`, process.env.PATH].join(";") },
  });
  const j = JSON.parse(out);
  return j.map((m) => (m.content || []).map((c) => c.text || "").join("\n")).join("\n");
}
const txt = render();
const roots = {};
for (const m of txt.matchAll(/^- `(r\d+)` = `([^`]+)`/gm)) roots[m[1]] = m[2];
const skills = [];
for (const m of txt.matchAll(/^- (\S+?):(?: [^\n]*?)? \(file: (r\d+)\/([^)]+)\)$/gm)) {
  skills.push({ name: m[1].trim(), path: roots[m[2]] + "/" + m[3] });
}
const drop = skills.filter((s) => !KEEP.has(s.name));
const kept = skills.filter((s) => KEEP.has(s.name));
const missing = [...KEEP].filter((k) => !skills.some((s) => s.name === k));
console.log(`catalogue ${skills.length} skills, keep ${kept.length}, disable ${drop.length}`);
if (missing.length) console.log("KEEP names not found (check spelling or plugin enabled):", missing.join(", "));

const block = [BEGIN, ...drop.map((s) => `[[skills.config]]\npath = "${s.path}"\nenabled = false\n`), END, ""].join("\n");
if (dry) { console.log("dry run, config untouched"); process.exit(0); }
fs.writeFileSync(CFG, clean.replace(/\n*$/, "\n\n") + block);
console.log("wrote", drop.length, "disable entries to", CFG);
